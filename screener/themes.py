def tag_themes(name: str) -> list[str]:
    """銘柄名から該当する投資テーマのキー一覧を返す(先頭一致)。

    部分一致だと短い社名が別銘柄の途中に含まれて誤爆する
    (例: 「ローム」→「ヒューマン・メタボローム・テクノロジーズ」)ため先頭一致。
    """
    name = name or ""
    return [theme for theme, kws in THEME_NAME_KEYWORDS.items() if any(name.startswith(k) for k in kws)]
